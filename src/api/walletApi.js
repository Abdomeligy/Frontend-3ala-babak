import axiosClient from './axiosClient';

/* ============================================================
   CUSTOMER WALLET
============================================================ */

const customerWalletApi = {
  /**
   * GET CUSTOMER WALLET BALANCE
   */
  getBalance: async () => {
    const res = await axiosClient.get('/customer-wallet/balance');

    return res.data;
  },

  /**
   * GET CUSTOMER WALLET TRANSACTIONS
   */
  getTransactions: async () => {
    const res = await axiosClient.get('/customer-wallet/transactions');

    return res.data;
  },

  /**
   * CHARGE CUSTOMER WALLET
   */
  charge: async (amount) => {
    const amountString = String(amount).trim().replace(',', '.');

    if (!/^\+?(?:\d+)(?:\.\d{1,2})?$/.test(amountString)) {
      throw new Error('A valid amount is required');
    }

    const numericAmount = Number(amountString);

    if (!Number.isFinite(numericAmount) || numericAmount <= 0 || numericAmount > 100000) {
      throw new Error('A valid amount is required');
    }

    const res = await axiosClient.post(
      '/customer-wallet/charge',
      {
        amount: numericAmount,
      }
    );

    return res.data;
  },

  /**
   * GET FULL CUSTOMER WALLET
   */
  getWallet: async () => {
    const [balanceRes, transactionsRes] = await Promise.all([
      axiosClient.get('/customer-wallet/balance'),
      axiosClient.get('/customer-wallet/transactions'),
    ]);

    return {
      balance: balanceRes.data,
      transactions: transactionsRes.data,
    };
  },
};


/* ============================================================
   DRIVER WALLET
============================================================ */

const driverWalletApi = {
  /**
   * GET DRIVER WALLET
   *
   * GET /api/wallet/:driverId
   */
  getWallet: async (driverId) => {
    const numericDriverId = Number(driverId);

    if (!Number.isInteger(numericDriverId) || numericDriverId <= 0) {
      throw new Error('driverId is required');
    }

    const res = await axiosClient.get(
      `/wallet/${numericDriverId}`
    );

    return res.data;
  },

  /**
   * GET DRIVER BALANCE
   *
   * Backend currently returns the wallet object from:
   *
   * GET /api/wallet/:driverId
   */
  getBalance: async (driverId) => {
    const numericDriverId = Number(driverId);

    if (!Number.isInteger(numericDriverId) || numericDriverId <= 0) {
      throw new Error('driverId is required');
    }

    const res = await axiosClient.get(
      `/wallet/${numericDriverId}`
    );

    return res.data;
  },

  /**
   * REQUEST DRIVER WITHDRAWAL
   *
   * POST /api/wallet/withdraw
   *
   * Backend expects:
   *
   * {
   *   driverId,
   *   amount
   * }
   *
   * reference is generated by Backend.
   *
   * Supports both:
   *
   * requestWithdrawal(driverId, amount)
   *
   * and:
   *
   * requestWithdrawal({
   *   driverId,
   *   amount
   * })
   */
  requestWithdrawal: async (arg1, arg2) => {
    let driverId;
    let amount;

    /* --------------------------------------------------------
       OBJECT FORMAT
       -------------------------------------------------------- */

    if (
      typeof arg1 === 'object' &&
      arg1 !== null
    ) {
      driverId =
        arg1.driverId ??
        arg1.driver_id;

      amount = arg1.amount;
    }

    /* --------------------------------------------------------
       OLD / BACKWARD COMPATIBILITY FORMAT
       requestWithdrawal(driverId, amount)
       -------------------------------------------------------- */

    else {
      driverId = arg1;
      amount = arg2;
    }

    const numericDriverId = Number(driverId);
    const numericAmount = Number(amount);

    /* --------------------------------------------------------
       DRIVER ID VALIDATION
       -------------------------------------------------------- */

    if (
      !Number.isInteger(numericDriverId) ||
      numericDriverId <= 0
    ) {
      throw new Error('driverId is required');
    }

    /* --------------------------------------------------------
       AMOUNT VALIDATION
       -------------------------------------------------------- */

    if (
      !Number.isFinite(numericAmount) ||
      numericAmount <= 0
    ) {
      throw new Error(
        'A valid withdrawal amount is required'
      );
    }

    /* --------------------------------------------------------
       ROUND TO 2 DECIMAL PLACES
       -------------------------------------------------------- */

    const normalizedAmount =
      Number(numericAmount.toFixed(2));

    /* --------------------------------------------------------
       SEND REQUEST
       
       IMPORTANT:
       Do NOT generate reference here.
       
       Backend generates:
       wd_<driverId>_<timestamp>_<random>
       -------------------------------------------------------- */

    const res = await axiosClient.post(
      '/wallet/withdraw',
      {
        driverId: numericDriverId,
        amount: normalizedAmount,
      }
    );

    return res.data;
  },
};


